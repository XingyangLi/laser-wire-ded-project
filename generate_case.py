    def mesh_spec(self):
        a, dx = self.a, self.dx
        # x: [x0, xa] graded coarse->fine, [xa, xb] uniform, [xb, x1] fine->coarse
        x_lo = min(self.x_wire_top - self.R / math.sin(self.th) - 0.3e-3, a.laser_x - 2.5e-3)
        xa = max(self.x0, x_lo)
        xb = min(self.x1, a.laser_x + max(a.downstream - 2.0e-3, 2.5e-3))
        if a.uniform_downstream:
            xb = min(self.x1 - 2 * dx, a.laser_x + a.uniform_downstream)
        secs = []
        if xa - self.x0 > 1e-9:
            n = graded(xa - self.x0, dx, 2.0)
            secs.append((xa - self.x0, n, 0.5))
        secs.append((xb - xa, max(1, round((xb - xa) / dx)), 1.0))
        if self.x1 - xb > 1e-9:
            n = graded(self.x1 - xb, dx, 3.0)
            secs.append((self.x1 - xb, n, 3.0))
        self.xsec = secs
        # y
        if self.d2:
            self.ysec = [(dx, 1, 1.0)]
            self.y1 = dx
        else:
            yf = min(a.half_width, max(2.2e-3, 1.4 * a.spot_radius + 0.5e-3))
            ys = [(yf, max(1, round(yf / dx)), 1.0)]
            if a.half_width - yf > 1e-9:
                ys.append((a.half_width - yf, graded(a.half_width - yf, dx, 3.0), 3.0))
            if self.full:   # mirror image of the half-domain grading
                ys = [(L_, n_, 1.0 / r_) for L_, n_, r_ in reversed(ys)] + ys
            self.ysec = ys
            self.y1 = a.half_width
        # z substrate: [zb, -zf] coarse->fine (ratio 1/4), [-zf, 0] uniform
        zf = min(0.8e-3, -self.zb)
        zs = []
        if -self.zb - zf > 1e-9:
            zs.append((-self.zb - zf, graded(-self.zb - zf, dx, 4.0), 0.25))
        zs.append((zf, max(1, round(zf / dx)), 1.0))
        self.zsub = zs
        zg = min(self.zt, self.gas_uniform)
        zgs = [(zg, max(1, round(zg / dx)), 1.0)]
        if self.zt - zg > 1e-9:
            zgs.append((self.zt - zg, graded(self.zt - zg, dx, 2.0), 2.0))
        self.zgas = zgs
        nx = sum(s[1] for s in self.xsec)
        ny = sum(s[1] for s in self.ysec)
        nzs = sum(s[1] for s in self.zsub)
        nzg = sum(s[1] for s in self.zgas)
        self.n = (nx, ny, nzs, nzg)
        self.ncells_block = nx * ny * (nzs + nzg)
        self.ncells = self.ncells_block
        self.n_refine_cols = 0
        if a.wire_refine > 0:
            # columns whose centre lies inside the refinement box (uniform core spacing dx there)
            hw = a.refine_halfwidth
            hwy = a.refine_halfwidth_y or hw
            ncx = 2 * int(math.floor(hw / dx + 0.5)) + int(math.floor(a.refine_downstream / dx + 0.5))
            ncy = 2 * int(math.floor(hwy / dx + 0.5)) if self.full else int(math.floor(hwy / dx + 0.5))
            self.n_refine_cols = ncx * ncy
            nz = nzs + nzg
            split = 8 if a.wire_refine_z else 4
            self.ncells = self.ncells_block + self.n_refine_cols * nz * (split ** a.wire_refine - 1)

    @staticmethod
    def grading(secs):
        if len(secs) == 1:
            return f(secs[0][2])
        L = sum(s[0] for s in secs)
        N = sum(s[1] for s in secs)
        return "(" + " ".join(f"({f(s[0]/L)} {f(s[1]/N)} {f(s[2])})" for s in secs) + ")"

