    def block_mesh(self):
        x0, x1, y0, y1, zb, zt = self.x0, self.x1, (-self.y1 if self.full else 0.0), self.y1, self.zb, self.zt
        nx, ny, nzs, nzg = self.n
        V = [(x0, y0, zb), (x1, y0, zb), (x1, y1, zb), (x0, y1, zb),
             (x0, y0, 0), (x1, y0, 0), (x1, y1, 0), (x0, y1, 0),
             (x0, y0, zt), (x1, y0, zt), (x1, y1, zt), (x0, y1, zt)]
        gx, gy = self.grading(self.xsec), self.grading(self.ysec)
        b1 = f"    hex (0 1 2 3 4 5 6 7) ({nx} {ny} {nzs}) simpleGrading ({gx} {gy} {self.grading(self.zsub)})"
        b2 = f"    hex (4 5 6 7 8 9 10 11) ({nx} {ny} {nzg}) simpleGrading ({gx} {gy} {self.grading(self.zgas)})"
        side_t = "empty" if self.d2 else "patch"
        sym_t = "empty" if self.d2 else "symmetryPlane"
        pat = [
            ("inletSubstrate", "patch", ["(0 4 7 3)"]),
            ("inletGas", "patch", ["(4 8 11 7)"]),
            ("outlet", "patch", ["(1 2 6 5)", "(5 6 10 9)"]),
            ("bottom", "wall", ["(0 3 2 1)"]),
            ("top", "patch", ["(8 9 10 11)"]),
        ]
        if self.d2:
            pat.append(("frontAndBack", "empty", ["(0 1 5 4)", "(4 5 9 8)", "(3 7 6 2)", "(7 11 10 6)"]))
        elif self.full:
            pat.append(("side", side_t, ["(0 1 5 4)", "(4 5 9 8)", "(3 7 6 2)", "(7 11 10 6)"]))
        else:
            pat.append(("symmetry", sym_t, ["(0 1 5 4)", "(4 5 9 8)"]))
            pat.append(("side", side_t, ["(3 7 6 2)", "(7 11 10 6)"]))
        bnd = "\n".join(f"    {n}\n    {{\n        type {t};\n        faces\n        (\n            "
                        + "\n            ".join(fc) + "\n        );\n    }" for n, t, fc in pat)
        txt = header("dictionary", "blockMeshDict", "system")
        txt += f"// LW-DED domain, {self.ncells_block} block cells (core dx = {self.dx*1e6:.0f} um)"
        txt += (f", {self.ncells} after the wire-box refinement\n" if self.a.wire_refine else "\n")
        txt += "// block 0: substrate (z<0), block 1: shielding gas (z>0); identical x/y grading\n"
        txt += "// so that cells form vertical columns (required by the ray-traced laser)\n\n"
        txt += "scale 1;\n\nvertices\n(\n" + "\n".join(f"    {vec(*v)}" for v in V) + "\n);\n\n"
        txt += "blocks\n(\n" + b1 + "\n" + b2 + "\n);\n\nedges\n(\n);\n\nboundary\n(\n" + bnd + "\n);\n\n"
        txt += "mergePatchPairs\n(\n);\n" + FOOT
        return txt

    def wire_cyl(self, s_lo, s_hi, r):
        o, u = self.origin, self.up
