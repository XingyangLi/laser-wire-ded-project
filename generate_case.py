    def components_block(self):
        a = self.a
        out = ["components      // multi-component wire (one tracer c<name> + unmelted marker u<name> each)", "{",
               "    enabled     true;",
               f"    names       ({' '.join(self.comp_names)});",
               f"    substrateNi {f(self.ms.get('Ni_wt', 0.0))};   // wt.% Ni of the substrate ({a.substrate_material})",
               f"    meltedFollowsSubstrate {'false' if a.no_melted_follow_substrate else 'true'};",
               "    unmeltedResetFl 0.5;   // u<name> -> 0 where the liquid fraction exceeds this",
               f"    wireStubbing {'false' if a.no_wire_stubbing else 'true'};   // solid wire cannot be pushed into solid substrate",
               f"    stubContactDist {f(1.6 * self.dx)};   // wire cells (centres) closer than this above the solid-support cell centre are dragged (= first cell above it)"]
        if a.stub_floor:
            out.append(f"    stubFloorZ {f(-0.5 * self.dx)};   // minimum support height (~ top substrate cell centre): "
                       "solid never-molten strands are not driven below the plate line")
        if getattr(a, "conservative_tracers", False):
            out.append("    conservativeTracers true;   // gas-cell extension of c_i/u_i for the face values "
                       "(no relabelling of wire metal as substrate at the free surface)")
            out.append("    tracerExtensionAlpha 0.01;  // cells below this metal fraction carry the neighbour composition")
            out.append("    tracerAlphaMin 1e-6;        // c = (alpha c)/alpha above this, extension value below")
        if getattr(a, "conservative_tracers", False) or getattr(a, "tracer_budget", False):
            out.append("    tracerBudget true;          // postProcessing/meltPool/tracerBudget.dat")
        for c in self.comp_names:
            m = MATERIALS[c]
            if a.absorptivity_wire is not None:
                Ac = a.absorptivity_wire
            elif a.absorptivity is not None:
                Ac = a.absorptivity
            else:
                Ac = m["absorptivity"]
            ks = m["k_solid"] * self.strand_k_factor
            out += [f"    {c}", "    {",
                    f"        cp {f(m['cp'])}; k {f(ks)}; kLiquid {f(m['k_liquid'])}; L {f(m['L'])};",
                    f"        Tsolidus {f(m['Tsol'])}; Tliquidus {f(m['Tliq'])};",
                    f"        sigma {f(m['sigma'])}; dSigmadT {f(m['dsigma_dT'])};",
                    f"        absorptivity {f(Ac)};",
                    f"        Ni {f(m.get('Ni_wt', 0.0))};", "    }"]
        if a.liquidus == "table":
            out.append("    // Fe-Ni phase diagram: (wt%Ni Tsolidus Tliquidus), see materials.py")
            out.append("    liquidusTable (" + " ".join(f"({f(w)} {f(ts)} {f(tl)})" for w, ts, tl in FE_NI_LIQUIDUS) + ");")
        if self.liquidus_unmixed is not None:
            out.append(
                f"    liquidusUnmixedThreshold {f(self.liquidus_unmixed)};   "
                "// component Tsol/Tliq when max(c_i) exceeds this (pure Fe keeps 1811 K)"
            )
        if self.unmelted_k_factor != 1.0:
            out.append(
                f"    unmeltedKFactor {f(self.unmelted_k_factor)};   "
                "// multiply matKs in solid unmelted-wire cells"
            )
        out.append("}")
        return "\n".join(out) + "\n"

    def record_planes(self):
        """x positions of the y-z recording planes, snapped inside a fine cell (not on a face)."""
        a = self.a
        if a.record_x is not None:
            xs = [float(v) for v in a.record_x.split(",") if v.strip()]
        elif self.comp_names:
            xs = [2e-3, 3e-3, 4e-3, 5e-3]
        else:
            return []
        xa = self.x0 + (self.xsec[0][0] if len(self.xsec) > 1 else 0.0)
        out = []
        for x in xs:
            k = math.floor((x - xa) / self.dx)
            out.append(xa + (k + 0.25) * self.dx)   # a cell centre of the refined (dx/2) cells, inside a dx cell
        return out

