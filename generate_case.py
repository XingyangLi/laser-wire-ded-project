    def strand_geometry(self, Rw):
        """equal round strands: optional centre strand + a ring of n strands, outer envelope = wire radius."""
        a = self.a
        N, g = a.strands, a.strand_gap
        if N < 2:
            raise SystemExit("--strands must be >= 2")
        centre = self.has_centre()
        n = N - 1 if centre else N
        s = math.sin(math.pi / n)
        if a.strand_diameter:
            r = a.strand_diameter / 2
            Rc = self.ring_radius_fixed(r)
        else:
            # ring-ring spacing: 2 Rc sin(pi/n) >= 2 r + g ; centre-ring: Rc >= 2 r + g ; Rc + r = Rw
            r_ring = (Rw - g / (2 * s)) / (1 + 1 / s)            # limited by ring neighbours
            r_cent = (Rw - g) / 3 if centre else float("inf")     # limited by the centre strand
            r = min(r_ring, r_cent)
            if r <= 0:
                raise SystemExit("strand gap too large for this wire diameter / strand count")
            Rc = Rw - r
        lay = a.lay_length if a.lay_length else 10.0 * a.wire_diameter
        a.lay_length = lay
        area = N * math.pi * r ** 2
        helix = math.degrees(math.atan(2 * math.pi * Rc / lay))
        return dict(n_strands=N, centre_strand=centre, n_ring=n, strand_radius=r, strand_diameter=2 * r,
                    envelope_diameter=2 * (Rc + r), central_gap_diameter=(2 * (Rc - r) if not centre else 0.0),
                    ring_radius=Rc, gap=g, lay_length=lay, lay_direction=a.lay_direction,
                    helix_angle_deg=helix, area=area, fill_factor=area / self.Aw,
                    cells_per_strand_diameter=2 * r / (self.dx / 2 ** a.wire_refine))

    def has_centre(self):
        a = self.a
        if a.strand_layout == "ring":
            return False
        if a.strand_layout == "centre":
            return True
        return a.strands >= 4

    def ring_radius_fixed(self, r):
        """ring radius for a fixed strand radius r: neighbours (and the centre strand) gap = strand gap."""
        a = self.a
        g = a.strand_gap
        n = a.strands - 1 if self.has_centre() else a.strands
        Rc = (2 * r + g) / (2 * math.sin(math.pi / n)) if n >= 2 else 0.0
        if self.has_centre():
            Rc = max(Rc, 2 * r + g)
        return Rc

    def envelope_diameter(self):
        r = self.a.strand_diameter / 2
        return 2 * (self.ring_radius_fixed(r) + r)

    def setup_components(self):
        """multi-component wire: per-material strand index lists, area/mass shares, mixture properties."""
        a, st = self.a, self.strands
        mats = a.strand_material_list
        centre = st["centre_strand"]
        ring_mats = mats[1:] if centre else mats
        self.centre_mat = mats[0] if centre else None
        self.ring_mats = ring_mats
        area1 = math.pi * st["strand_radius"] ** 2
        share = {c: mats.count(c) / len(mats) for c in self.comp_names}            # area (volume) share
        rho_rt = {c: MATERIALS[c].get("rho_rt", MATERIALS[c]["rho"]) for c in self.comp_names}
        mass = {c: share[c] * rho_rt[c] for c in self.comp_names}
        mtot = sum(mass.values())
        self.comp_area_share = share
        self.comp_mass_share = {c: mass[c] / mtot for c in self.comp_names}
        self.comp_area = {c: mats.count(c) * area1 for c in self.comp_names}
        wni = sum(self.comp_mass_share[c] * MATERIALS[c].get("Ni_wt", 0.0) for c in self.comp_names)
        self.wire_Ni_wt = wni
        # area-weighted mixture of the strand materials (used for rho, mu, vapour, sigma bounds)
        keys = [k for k, v in MATERIALS[self.comp_names[0]].items() if isinstance(v, float)]
        mix = {k: sum(share[c] * MATERIALS[c].get(k, 0.0) for c in self.comp_names) for k in keys}
        self.mw = mix
        self.m = mix

    def wire_basis(self):
        """orthonormal (e1, e2, up) with up = tip -> feeder."""
        u = self.up
        e2 = (0.0, 1.0, 0.0)
        e1 = (u[2], 0.0, -u[0])
        return e1, e2, u

    def round_wire_vars(self, t_expr):
        """OpenFOAM variables for a solid round wire, shifted sideways when a weave is on."""
        a = self.a
        e1, e2, u = self.wire_basis()
        o = self.origin
        def lin(e):
            return (f"({f(e[0])})*(pos().x() - ({f(o[0])})) + ({f(e[1])})*(pos().y() - ({f(o[1])})) "
                    f"+ ({f(e[2])})*(pos().z() - ({f(o[2])}))")
        y_lin = lin(e2)
        var = []
        if self.weave_amp > 0:
            var.append(f"sTravel = {f(a.scan_speed)}*max({t_expr}, 0)")
            var.append(f"wFrac = sTravel/{f(self.weave_wavelength)} - floor(sTravel/{f(self.weave_wavelength)})")
            var.append(f"yw = {f(self.weave_amp)}*(1 - 4*sqrt(sqr(wFrac - 0.5)))")
            y_lin = f"({y_lin}) - yw"
        h = self.dx_min
        var += [f"X = {lin(e1)}", f"Y = {y_lin}", f"Z = {lin(u)}"]
        var.append(f"m = max(0, min(1, 0.5 + ({f(self.R)} - sqrt(X*X + Y*Y))/{f(h)}))")
        return var

    def strand_vars(self, t_expr):
        """OpenFOAM expression variables: wire-local X, Y, axial Z, helix phase ph and metal fraction m."""
        a, st = self.a, self.strands
        e1, e2, u = self.wire_basis()
        o = self.origin
        def lin(e):
            return (f"({f(e[0])})*(pos().x() - ({f(o[0])})) + ({f(e[1])})*(pos().y() - ({f(o[1])})) "
                    f"+ ({f(e[2])})*(pos().z() - ({f(o[2])}))")
        t0, t1 = a.feed_start, a.feed_start + 0.002
        v = a.wire_feed_speed
        hand = 1.0 if a.lay_direction == "right" else -1.0
        k = hand * 2 * math.pi / st["lay_length"]
        h = self.dx_min
        r, Rc = st["strand_radius"], st["ring_radius"]
        y_lin = lin(e2)
        var = []
        if self.weave_amp > 0:
            # triangular zigzag, same formula as the solver: yw in [-amplitude, +amplitude]
            # t = 0 starts at -amplitude (one corner of the zigzag)
            var.append(f"sTravel = {f(a.scan_speed)}*max({t_expr}, 0)")
            var.append(f"wFrac = sTravel/{f(self.weave_wavelength)} - floor(sTravel/{f(self.weave_wavelength)})")
            var.append(f"yw = {f(self.weave_amp)}*(1 - 4*sqrt(sqr(wFrac - 0.5)))")
            y_lin = f"({y_lin}) - yw"
        var += [f"X = {lin(e1)}", f"Y = {y_lin}", f"Z = {lin(u)}"]
        # fed length s(t) (linear ramp of the feed speed between t0 and t1, as the U inlet table)
        var.append(f"sf = {f(v)}*(pow(max({t_expr} - {f(t0)}, 0), 2) - pow(max({t_expr} - {f(t1)}, 0), 2))"
                   f"/{f(2*(t1-t0))}")
        # material coordinate Z + s: the helix is frozen in the wire, the wire moves down by s
        var.append(f"ph = {f(k)}*(Z + sf)")
        terms = []
        if st["centre_strand"]:
            terms.append(f"max(0, min(1, 0.5 + ({f(r)} - sqrt(X*X + Y*Y))/{f(h)}))")
        for i in range(st["n_ring"]):
            a_i = 2 * math.pi * i / st["n_ring"]
            terms.append(f"max(0, min(1, 0.5 + ({f(r)} - sqrt(sqr(X - {f(Rc)}*cos(ph + {f(a_i)})) "
                         f"+ sqr(Y - {f(Rc)}*sin(ph + {f(a_i)}))))/{f(h)}))")
        if self.comp_names:
            mats = self.a.strand_material_list
            for c in self.comp_names:
                tc = [t for t, mm in zip(terms, mats) if mm == c]
                var.append(f"m{c} = " + " + ".join(tc))
            var.append("msum = " + " + ".join(f"m{c}" for c in self.comp_names))
            var.append("m = min(1, msum)")
        else:
            var.append("m = min(1, " + " + ".join(terms) + ")")
        return var

