# ----------------------------------------------------------------------------
def header(cls, obj, loc=None):
    l = f'    location    "{loc}";\n' if loc else ""
    return ("/*--------------------------------*- C++ -*----------------------------------*\\\n"
            "| Generated by laser_wire_ded/generate_case.py (OpenFOAM.com v2406/v2412)    |\n"
            "\\*---------------------------------------------------------------------------*/\n"
            f"FoamFile\n{{\n    version     2.0;\n    format      ascii;\n    class       {cls};\n"
            f"{l}    object      {obj};\n}}\n"
            "// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //\n\n")


FOOT = "\n// ************************************************************************* //\n"


def f(x):
    return f"{x:.8g}"


def vec(*c):
    return "(" + " ".join(f(v) for v in c) + ")"


def write(path: Path, text: str, exe=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="\n") as fh:
        fh.write(text)
    if exe:
        path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


