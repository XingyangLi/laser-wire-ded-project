def csv_floats(text, name):
    """Comma-separated floats, or None if text is None."""
    if text is None:
        return None
    try:
        vals = [float(p) for p in str(text).split(",") if p.strip()]
    except ValueError as exc:
        raise SystemExit(f"{name} must be a comma-separated list of numbers, got {text!r}") from exc
    if not vals:
        raise SystemExit(f"{name} is empty")
    return vals


def fit_list(vals, n, name):
    if vals is None:
        return None
    if len(vals) == 1 and n > 1:
        return vals * n
    if len(vals) != n:
        raise SystemExit(f"{name} has {len(vals)} values for {n} beams")
    return vals


def graded(length, dx, ratio):
    """cells for a section starting at dx and growing by 'ratio' (last/first)."""
    n = max(1, round(length / (dx * (1 + ratio) / 2.0)))
    return n


# Dissolved oxygen [ppm by weight] and contact angles through the metal [deg]:
# plate receding, plate advancing, wire receding, wire advancing.
# PLACEHOLDER knots so a chamber-oxygen sweep moves the hysteresis window.
# Not a fit to sessile-drop data. Linear in ppm, clamped outside the ends.
# At 10 ppm the window is the historical 20/90 (plate) and 25/70 (wire).
# The upward trend stands in for an oxide film (poorer wetting, wider hysteresis)
# until advancing/receding angles are measured. See README.
OXYGEN_ANGLE_TABLE = (
    (10, 20, 90, 25, 70),
    (100, 28, 100, 35, 90),
    (500, 40, 120, 48, 115),
    (1000, 50, 130, 58, 130),
)

# Oxide film on the solid wire, not a sessile-drop fit. Columns [deg]:
# ppm, wire receding, wire advancing, trailing receding, trailing advancing.
# The plate window is not in this table. The front of the wire stays a
# wetting-to-intermediate window. The trailing face is the oxide: wetting
# at low ppm (receding well below 90 deg, so melt is pulled onto the wire)
# and non-wetting from 100 ppm up (receding 90–120, advancing 120–150).
# A receding floor below 90 deg accepts a wetted groove; one above 90 deg
# drives that meniscus back off the wire.
WIRE_OXIDE_TABLE = (
    (0, 25, 70, 25, 70),
    (50, 32, 80, 40, 85),
    (100, 42, 100, 90, 125),
    (300, 58, 125, 110, 145),
    (1000, 70, 140, 120, 150),
)


def oxide_wire_angles(ppm):
    """Return (wireR, wireA, trailR, trailA) [deg] at this oxygen level."""
    tab = WIRE_OXIDE_TABLE
    if ppm <= tab[0][0]:
        return tab[0][1:]
    if ppm >= tab[-1][0]:
        return tab[-1][1:]
    for lo, hi in zip(tab, tab[1:]):
        if ppm <= hi[0]:
            span = hi[0] - lo[0]
            w = (ppm - lo[0]) / span if span else 0.0
            return tuple(lo[i] + w * (hi[i] - lo[i]) for i in range(1, 5))
    return tab[-1][1:]


