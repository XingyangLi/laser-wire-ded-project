"""
generate_case.py - write an OpenFOAM.com (v2406/v2412) case for single-track
laser wire-feed DED (LW-DED) solved with laserWireDEDFoam.

Laboratory frame: the laser spot and the wire nozzle are fixed, the substrate
(and the deposited bead) move through the domain in +x with the scan speed
(substrate enters at x-min, leaves at x-max). The wire enters through a
'wireInlet' patch on the top boundary, front-fed (from the leading side).

    python generate_case.py                                   # 3D half-domain, 316L, 2 kW
    python generate_case.py --case c1 --power 2500 --scan-speed 0.008
    python generate_case.py --dim 2d --case c2d               # quasi-2D longitudinal section
    python generate_case.py --resolution coarse --end-time 0.1 --case trial
    python generate_case.py --material Ti6Al4V --feed-angle 35 --wire-diameter 1.2e-3
    python generate_case.py --print                           # derived values only
    python generate_case.py --laser-config transitional_r --wire-type stranded --case tr_str   # 7-strand wire

Only the Python standard library is needed.
"""
